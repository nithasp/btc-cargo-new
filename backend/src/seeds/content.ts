const toPlain = (html: string): string =>
  html
    .replace(/<[^>]+>/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

export async function seedContent(db: Queryable): Promise<void> {
  for (const content of CONTENTS) {
    const html = content.html.trim();
    await db.query(
      `INSERT INTO html_contents (key, html, plain) VALUES ($1, $2, $3)
       ON CONFLICT (key) DO UPDATE SET html = EXCLUDED.html, plain = EXCLUDED.plain`,
      [content.key, html, toPlain(html)],
    );
  }
}
